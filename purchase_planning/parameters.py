def llm_max_skus() -> int:
    try:
        limit = int(getenv("LLM_MAX_SKUS", ""))
    except ValueError:
        return DEFAULT_LLM_MAX_SKUS
    return limit if limit >= 0 else DEFAULT_LLM_MAX_SKUS


